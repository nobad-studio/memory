"""NOBAD shared memory: one small Markdown file per fact, plus a generated one-line-per-fact INDEX.md.

Standard library only. Commands (run from the repository root):
  python tools/mem.py index            rebuild INDEX.md from facts/
  python tools/mem.py check            validate every fact and the index (CI runs this)
  python tools/mem.py new SCOPE TYPE SLUG "One-line description"   scaffold a fact
  python tools/mem.py status           open PRs and recently pushed branches across nobad-studio (needs gh)
"""
import datetime
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FACTS = ROOT / "facts"
INDEX = ROOT / "INDEX.md"

SCOPES = ("org", "vpn", "find", "file-bridge", "website")
TYPES = ("decision", "open", "idea", "reference", "release")
TYPE_ORDER = {t: i for i, t in enumerate(TYPES)}
MAX_FACT_BYTES = 1500          # keeps every fact cheap to load
MAX_DESC = 160
SLUG = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
ORG = "nobad-studio"

# Things that must never land in a file every AI assistant loads.
SECRET_PATTERNS = [
    (re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"), "private key block"),
    (re.compile(r"(?im)^\s*PrivateKey\s*=\s*\S+"), "WireGuard PrivateKey line"),
    (re.compile(r"(?im)^\s*PresharedKey\s*=\s*\S+"), "WireGuard PresharedKey line"),
    (re.compile(r"\bgh[pousr]_[A-Za-z0-9]{20,}"), "GitHub token"),
    (re.compile(r"\bgithub_pat_[A-Za-z0-9_]{20,}"), "GitHub token"),
    (re.compile(r"\bsk-ant-[A-Za-z0-9_-]{20,}"), "Anthropic key"),
    (re.compile(r"\bAKIA[0-9A-Z]{16}\b"), "AWS key"),
    (re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}"), "Slack token"),
    (re.compile(r"(?i)\b(password|passwd|secret|api[_-]?key)\s*[:=]\s*\S{6,}"), "credential assignment"),
]


def parse(path):
    """Return (meta, body) for a fact file; raise ValueError if the front matter is malformed."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError("must start with a '---' front matter block")
    try:
        head, body = text[4:].split("\n---\n", 1)
    except ValueError:
        raise ValueError("front matter isn't closed with '---'") from None
    meta = {}
    for line in head.splitlines():
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise ValueError(f"bad front matter line: {line!r}")
        meta[key.strip()] = value.strip().strip('"')
    return meta, body.strip()


def facts():
    return sorted(FACTS.glob("*/*.md"))


def problems_for(path):
    out = []
    rel = path.relative_to(ROOT).as_posix()
    try:
        meta, body = parse(path)
    except ValueError as e:
        return [f"{rel}: {e}"]
    scope = path.parent.name
    for key in ("name", "description", "type", "date"):
        if not meta.get(key):
            out.append(f"{rel}: missing '{key}'")
    if scope not in SCOPES:
        out.append(f"{rel}: folder must be one of {', '.join(SCOPES)}")
    if meta.get("name") != path.stem:
        out.append(f"{rel}: name '{meta.get('name')}' must match the file name '{path.stem}'")
    if not SLUG.match(path.stem):
        out.append(f"{rel}: file name must be lowercase-kebab-case")
    if meta.get("type") and meta["type"] not in TYPES:
        out.append(f"{rel}: type must be one of {', '.join(TYPES)}")
    if meta.get("date") and not DATE.match(meta["date"]):
        out.append(f"{rel}: date must be YYYY-MM-DD")
    if len(meta.get("description", "")) > MAX_DESC:
        out.append(f"{rel}: description longer than {MAX_DESC} characters")
    if not body:
        out.append(f"{rel}: empty body")
    size = len(path.read_bytes())
    if size > MAX_FACT_BYTES:
        out.append(f"{rel}: {size} bytes, limit {MAX_FACT_BYTES}: split it or trim it")
    text = path.read_text(encoding="utf-8")
    for pat, what in SECRET_PATTERNS:
        if pat.search(text):
            out.append(f"{rel}: looks like a secret ({what}); memory is public and loaded by every assistant")
    return out


def render_index():
    rows = []
    for path in facts():
        meta, _ = parse(path)
        rows.append((path.parent.name, TYPE_ORDER.get(meta["type"], 99), meta["date"], path, meta))
    # Grouped by scope, then type; newest first inside a group.
    rows.sort(key=lambda r: (SCOPES.index(r[0]) if r[0] in SCOPES else 99, r[1], [-int(x) for x in r[2].split("-")]))
    lines = [
        "# NOBAD shared memory: index",
        "",
        "Generated by `python tools/mem.py index`; don't edit by hand. One line per fact: read this, then open only the",
        "facts that matter for your task. Format: `[type date] description (file)`.",
    ]
    scope = None
    for sc, _, _, path, meta in rows:
        if sc != scope:
            scope = sc
            lines += ["", f"## {sc}"]
        lines.append(f"- [{meta['type']} {meta['date']}] {meta['description']} ({path.relative_to(ROOT).as_posix()})")
    return "\n".join(lines) + "\n"


def cmd_index():
    INDEX.write_text(render_index(), encoding="utf-8", newline="\n")
    print(f"INDEX.md: {len(facts())} facts")


def cmd_check():
    problems = []
    names = {}
    for path in facts():
        problems += problems_for(path)
        names.setdefault(path.stem, []).append(path.relative_to(ROOT).as_posix())
    for name, paths in names.items():
        if len(paths) > 1:
            problems.append(f"duplicate fact name '{name}': {', '.join(paths)}")
    for path in ROOT.joinpath("facts").glob("*.md"):
        problems.append(f"{path.relative_to(ROOT).as_posix()}: facts live in a scope folder (facts/<scope>/)")
    if not problems:
        if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != render_index():
            problems.append("INDEX.md is out of date: run `python tools/mem.py index` and commit it")
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    print(f"ok: {len(facts())} facts, index current")


def cmd_new(scope, typ, slug, description):
    if scope not in SCOPES or typ not in TYPES or not SLUG.match(slug):
        sys.exit(f"usage: new SCOPE({'|'.join(SCOPES)}) TYPE({'|'.join(TYPES)}) kebab-slug \"description\"")
    path = FACTS / scope / f"{slug}.md"
    if path.exists():
        sys.exit(f"{path.relative_to(ROOT)} already exists: update it instead")
    path.parent.mkdir(parents=True, exist_ok=True)
    today = datetime.date.today().isoformat()
    path.write_text(f"---\nname: {slug}\ndescription: {description}\ntype: {typ}\ndate: {today}\n---\n\n"
                    "<the fact in a few lines; for decisions add **Why:** and **How to apply:**>\n",
                    encoding="utf-8", newline="\n")
    print(f"created {path.relative_to(ROOT).as_posix()}: fill it in, then `python tools/mem.py index`")


def gh(*args):
    out = subprocess.run(["gh", *args], capture_output=True, text=True, encoding="utf-8")
    if out.returncode != 0:
        raise RuntimeError(out.stderr.strip() or "gh failed")
    return json.loads(out.stdout or "null")


def cmd_status():
    """Who is working on what: open PRs and branches pushed in the last 3 days, across the organization."""
    try:
        repos = gh("repo", "list", ORG, "--no-archived", "--limit", "50", "--json", "name")
    except (RuntimeError, FileNotFoundError) as e:
        sys.exit(f"needs the GitHub CLI (gh), logged in: {e}")
    since = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=3)
    for repo in sorted(r["name"] for r in repos):
        full = f"{ORG}/{repo}"
        prs = gh("pr", "list", "-R", full, "--state", "open", "--json", "number,title,author,headRefName,isDraft")
        branches = gh("api", f"repos/{full}/branches?per_page=100")
        fresh = []
        for b in branches:
            if b["name"] in ("main", "cla-signatures") or any(p["headRefName"] == b["name"] for p in prs):
                continue
            c = gh("api", f"repos/{full}/commits/{b['commit']['sha']}")
            when = datetime.datetime.fromisoformat(c["commit"]["committer"]["date"].replace("Z", "+00:00"))
            if when >= since:
                fresh.append(f"{b['name']} (last push {when:%Y-%m-%d}, {c['commit']['author']['name']})")
        if not prs and not fresh:
            continue
        print(f"## {full}")
        for p in prs:
            draft = " [draft]" if p["isDraft"] else ""
            print(f"- PR #{p['number']}{draft} {p['title']} ({p['author']['login']}, branch {p['headRefName']})")
        for f in fresh:
            print(f"- branch without PR: {f}")


def main(argv):
    if len(argv) >= 2 and argv[1] == "index":
        cmd_index()
    elif len(argv) >= 2 and argv[1] == "check":
        cmd_check()
    elif len(argv) == 6 and argv[1] == "new":
        cmd_new(*argv[2:])
    elif len(argv) >= 2 and argv[1] == "status":
        cmd_status()
    else:
        print(__doc__)
        sys.exit(2)


if __name__ == "__main__":
    main(sys.argv)
